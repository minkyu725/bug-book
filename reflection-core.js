export const CHOICE_POOLS = {morning:[1,2,4,12,13,16,17], evening:[3,5,7,11,15,20,22]};
export function choiceQuestions(slot) {
  return CHOICE_POOLS[slot].map(id => ({questionId:id, theme:QUESTIONS.find(q => q.id === id).theme,
    question:focusedQuestions[id].question,
    context:[focusedQuestions[id].helper, '오늘 또는 최근의 구체적인 장면 하나를 근거로 적어주세요. 떠오르지 않으면 ‘아직 관찰하지 못함’이라고 남겨도 괜찮아요.'].filter(Boolean).join(' ')}));
}
// Sunday through Saturday; the reflection day still changes at 05:30 Seoul time.
export const WEEKDAY_PAIRS = [[2,5],[4,7],[12,11],[13,15],[16,20],[17,22],[1,3]];
export function suggestedQuestion(day, slot) {
  const weekday = new Date(day + 'T00:00:00Z').getUTCDay();
  const id = WEEKDAY_PAIRS[weekday][slot === 'morning' ? 0 : 1];
  return choiceQuestions(slot).find(q => q.questionId === id);
}
export function choiceStats(logs, slot) {
  const answers = logs.filter(log => log.reflection?.type === 'answer' && log.reflection.choiceVersion === 1 && log.reflection.slot === slot && CHOICE_POOLS[slot].includes(log.reflection.questionId));
  return choiceQuestions(slot).map(q => {
    const count = answers.filter(log => log.reflection.questionId === q.questionId).length;
    return {...q, count, percent:answers.length ? Math.round(count / answers.length * 100) : 0};
  });
}
const order = [2, 7, 5, 13, 17, 3, 1, 4, 6, 9, 10, 8, 11, 12, 14, 15, 16, 18, 19, 20, 21, 22, 23];
export function seoulDay(date = new Date()) {
  return new Intl.DateTimeFormat('en-CA', {timeZone:'Asia/Seoul', year:'numeric', month:'2-digit', day:'2-digit'}).format(date);
}
// Shift the calendar by 5h30m so each reflection day starts at 05:30 in Seoul.
export function reflectionDay(date = new Date()) {
  return seoulDay(new Date(date.getTime() - 330 * 60000));
}
export function currentSlot(date = new Date()) {
  const hour = Number(new Intl.DateTimeFormat('en-GB', {timeZone:'Asia/Seoul', hour:'2-digit', hourCycle:'h23'}).format(date));
  const minute = Number(new Intl.DateTimeFormat('en-GB', {timeZone:'Asia/Seoul', minute:'2-digit'}).format(date));
  const minutes = hour * 60 + minute;
  return minutes >= 17 * 60 + 30 || minutes < 5 * 60 + 30 ? 'evening' : 'morning';
}
export function questionFor(day, slot) {
  const index = Math.floor(Date.parse(day + 'T00:00:00Z') / 86400000);
  if (day >= FOCUSED_START) {
    const offset = index - Math.floor(Date.parse(FOCUSED_START + 'T00:00:00Z') / 86400000);
    const id = FOCUSED_ORDER[slot][offset % 5], q = QUESTIONS.find(item => item.id === id);
    const focused = focusedQuestions[id];
    return {questionId:id, theme:q.theme, question:focused.question, context:[focused.helper, '오늘 또는 최근의 구체적인 장면 하나를 근거로 적어주세요. 떠오르지 않으면 ‘아직 관찰하지 못함’이라고 남겨도 괜찮아요.'].filter(Boolean).join(' ')};
  }
  const id = order[((index * 2 + (slot === 'evening' ? 1 : 0)) % order.length + order.length) % order.length];
  const q = QUESTIONS.find(item => item.id === id);
  const context = ['최근 일주일의 구체적인 장면을 떠올려 보세요.', '일이나 공부뿐 아니라 관계와 휴식에서도 찾아보세요.', '누구와 있었고 어떤 조건이었는지도 떠올려 보세요.'][Math.floor(index / 23) % 3];
  return {questionId:q.id, theme:q.theme, question:q[slot], context:slot === 'morning' ? context : '크고 작은 일 중 한 장면이면 충분해요.'};
}
// Only today's latest available question is due; skipped days never form a backlog.
export function dueReflection(logs, date = new Date()) {
  const slot = currentSlot(date), day = reflectionDay(date);
  if (!slot || logs.some(log => log.reflection?.type === 'answer' && log.reflection.day === day && log.reflection.slot === slot)) return null;
  return {day, slot, ...suggestedQuestion(day, slot)};
}
export function reflectionGroups(logs) {
  const answers = logs.filter(log => log.reflection?.type === 'answer').sort((a,b) => a.date.localeCompare(b.date) || a.id.localeCompare(b.id));
  return Array.from({length:Math.floor(answers.length / 7)}, (_, i) => answers.slice(i * 7, i * 7 + 7));
}
export function validateReflection(value) {
  if (!value || !['answer','feedback','review'].includes(value.type)) return false;
  if (value.type === 'answer') return QUESTIONS.some(q => q.id === value.questionId) && ['morning','evening'].includes(value.slot) &&
    typeof value.day === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(value.day) && Number.isFinite(Date.parse(value.day + 'T00:00:00Z')) && new Date(value.day + 'T00:00:00Z').toISOString().slice(0,10) === value.day &&
    typeof value.question === 'string' && value.question.length > 0 && value.question.length <= 1000;
  if (value.type === 'feedback') return typeof value.person === 'string' && value.person.trim().length > 0 && value.person.length <= 100 &&
    typeof value.question === 'string' && value.question.length > 0 && value.question.length <= 1000;
  return Array.isArray(value.answerIds) && value.answerIds.length === 7 && new Set(value.answerIds).size === 7 && value.answerIds.every(id => typeof id === 'string' && id.length > 0 && id.length <= 100);
}
